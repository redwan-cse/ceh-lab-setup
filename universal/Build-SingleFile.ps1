<# Rebuild Start-CehLab.ps1 from the reviewed Windows source files. No credentials. #>
[CmdletBinding()]
param()
$ErrorActionPreference = 'Stop'
$files = @('setup-openssh-windows-universal.ps1','Setup-ShellGPT-StepFun.ps1',
    'shellgpt_stepfun_setup.py','shellgpt_command_guard.py','shellgpt_command_policy.ps1',
    'test_command_guard.py','test_setup_safety.py','verify_shellgpt_live.py')
$payload = [ordered]@{}
foreach ($name in $files) {
    $path = Join-Path (Join-Path $PSScriptRoot 'windows') $name
    if (-not (Test-Path -LiteralPath $path)) { throw "Missing Windows source: $name" }
    $source = [IO.File]::ReadAllText($path).Replace("`r`n", "`n")
    $payload[$name] = [Convert]::ToBase64String([Text.Encoding]::UTF8.GetBytes($source))
}
$json = $payload | ConvertTo-Json -Compress
$template = @'
<#
Standalone CEH Windows lab setup. Generated by Build-SingleFile.ps1 from the
reviewable files in universal/windows. No passwords or API keys are embedded.
Run from an elevated Windows PowerShell console on the target machine.
NIC addresses, subnet masks, routes, gateways and DNS are never changed.
Default SSH firewall scope Any is intended for temporary, authorized lab VMs.
Use -AllowedClients <client-IP-or-CIDR> to restrict it.
#>
[CmdletBinding()]
param(
    [string[]]$AllowedClients = @('Any'),
    [ValidateRange(1,65535)][int]$SshPort = 22,
    [ValidateSet('Auto','MSI','Capability')][string]$InstallMethod = 'Auto',
    [switch]$SkipSsh,
    [switch]$SkipShellGpt,
    [switch]$NoApiKeyPrompt,
    [switch]$EnableLabAuthTuning
)
$ErrorActionPreference = 'Stop'
$ProgressPreference = 'SilentlyContinue'
if (-not $SkipSsh) {
    $principal = New-Object Security.Principal.WindowsPrincipal([Security.Principal.WindowsIdentity]::GetCurrent())
    if (-not $principal.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)) {
        throw 'Run Windows PowerShell as Administrator, or use -SkipSsh for per-user ShellGPT only.'
    }
}
$kitFolder = Join-Path ([IO.Path]::GetTempPath()) ('ceh-kit-' + [guid]::NewGuid().ToString('N'))
New-Item -ItemType Directory -Path $kitFolder | Out-Null
$payload = ConvertFrom-Json -InputObject '__PAYLOAD_JSON__'
foreach ($property in $payload.PSObject.Properties) {
    if ($property.Name -notmatch '^[a-zA-Z0-9_.-]+$') { throw 'Invalid embedded source filename.' }
    [IO.File]::WriteAllBytes((Join-Path $kitFolder $property.Name), [Convert]::FromBase64String($property.Value))
}
Write-Host "Setup source extracted to $kitFolder"
if (-not $SkipSsh) {
    & (Join-Path $kitFolder 'setup-openssh-windows-universal.ps1') -AllowedClients $AllowedClients -Port $SshPort -InstallMethod $InstallMethod -EnableLabAuthTuning:$EnableLabAuthTuning
}
if (-not $SkipShellGpt) {
    & (Join-Path $kitFolder 'Setup-ShellGPT-StepFun.ps1') -PromptForApiKey:(-not $NoApiKeyPrompt)
}
Write-Host 'CEH lab setup finished. Open a new terminal before using sgpt.'
Write-Host "To run live checks after configuring a key: python `"$(Join-Path $kitFolder 'verify_shellgpt_live.py')`""
'@
# JSON contains only fixed filenames and Base64 strings; no quote characters
# that could escape the single-quoted payload literal in the generated script.
$output = $template.Replace('__PAYLOAD_JSON__', $json)
$destination = Join-Path $PSScriptRoot 'Start-CehLab.ps1'
[IO.File]::WriteAllText($destination, $output, (New-Object Text.UTF8Encoding($false)))
$parseErrors=$null; $tokens=$null
[Management.Automation.Language.Parser]::ParseFile($destination,[ref]$tokens,[ref]$parseErrors) | Out-Null
if ($parseErrors.Count) { throw "Generated launcher failed syntax validation: $parseErrors" }
Get-Item -LiteralPath $destination | Select-Object FullName,Length
